# MODEL 2 — Priority Queue Index
# ═════════════════════════════════════════════════════════════
# Input:  risk_score, age, days_waiting
# Output: priority_index (higher = seen sooner)

def priority_index(risk_score: float, age: int, days_waiting: int) -> dict:
    age_risk  = 50 if (age >= 60 or age <= 5) else 25
    wait_norm = min(days_waiting / 7, 1.0) * 100

    index = (0.6 * risk_score) + (0.2 * age_risk) + (0.2 * wait_norm)
    index = round(index, 2)

    if index >= 70:   label = "Urgent"
    elif index >= 45: label = "Priority"
    else:             label = "Routine"

    return {"priority_index": index, "queue_label": label}

