# MODEL 5 — Outbreak Early Warning (MAIN AI MODEL)
# ═════════════════════════════════════════════════════════════
# Stage A: Exponential smoothing → expected baseline
# Stage B: Z-score anomaly detection → outbreak probability
# Input:  ward_name, daily_cases list
# Output: zone (RED/YELLOW/GREEN), outbreak_prob, z_score, baseline

def exp_smooth(series: list, alpha: float = 0.3) -> list:
    smoothed = [series[0]]
    for i in range(1, len(series)):
        s = alpha * series[i] + (1 - alpha) * smoothed[-1]
        smoothed.append(round(s, 2))
    return smoothed

def forecast_next_n(smoothed: list, actual: list, n_days: int = 7) -> list:
    """Simple forward forecast using trend from last 3 days"""
    last = smoothed[-1]
    if len(actual) >= 3:
        trend = (actual[-1] - actual[-3]) / 2
    else:
        trend = 0
    forecast = []
    for _ in range(n_days):
        last = last * 0.7 + (last + trend) * 0.3
        forecast.append(max(0, round(last)))
    return forecast

def outbreak_warning(ward_name: str, daily_cases: list) -> dict:
    if len(daily_cases) < 7:
        return {"error": "Need at least 7 days"}

    # Stage A — baseline via exponential smoothing
    smoothed = exp_smooth(daily_cases)
    baseline = smoothed[-1]
    actual   = daily_cases[-1]

    # Stage B — z-score on last 7 days
    window   = daily_cases[-7:]
    mean     = np.mean(window)
    std      = np.std(window) if np.std(window) > 0 else 1.0
    z        = (actual - mean) / std

    # Sigmoid → outbreak probability
    prob = round(1 / (1 + np.exp(-z)) * 100, 1)

    # Zone classification
    if prob >= 75:   zone = "RED"
    elif prob >= 55: zone = "YELLOW"
    else:            zone = "GREEN"

    # 7-day forecast
    forecast = forecast_next_n(smoothed, daily_cases, n_days=7)

    return {
        "ward":          ward_name,
        "actual":        actual,
        "baseline":      round(baseline, 1),
        "z_score":       round(z, 3),
        "outbreak_prob": prob,
        "zone":          zone,
        "forecast_7d":   forecast,
    }

