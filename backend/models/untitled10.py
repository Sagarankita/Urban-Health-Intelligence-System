SYNDROME_ADVISORIES = {
    "respiratory": [
        "Distribute N95 masks at PHCs in affected wards",
        "Screen for TB co-infection in prolonged fever cases",
        "Issue ventilation advisory for high-density housing",
    ],
    "vector_borne": [
        "Launch mosquito fogging operations in RED/YELLOW zones",
        "Issue water stagnation advisory — check coolers and containers",
        "Distribute mosquito nets and repellent at PHCs",
        "Activate rapid dengue/malaria test camps",
    ],
    "gastrointestinal": [
        "Test water supply quality — possible source contamination",
        "Distribute ORS and zinc packets at ward level",
        "Inspect food stalls, tiffin centres, and water tankers",
        "Coordinate with Pune Municipal Corporation for sanitation drive",
    ],
}

def generate_advisory(
    zone:               str,
    syndrome:           str,
    hospital_load_pct:  float,
    water_quality_issue: int  = 0,
    sanitation_score:   int  = 5,
) -> list:
    advisories = []

    # Zone-based actions
    if zone == "RED":
        advisories += [
            "[URGENT] Activate district outbreak response team",
            "[URGENT] Alert District Health Officer and CMO immediately",
            "Increase OPD capacity by 40% in affected wards",
            "Deploy field investigation teams within 24 hours",
            "Arrange emergency testing camps in high-density areas",
        ]
    elif zone == "YELLOW":
        advisories += [
            "Elevate monitoring to daily case review",
            "Pre-stock medications, ORS, and IV fluids at PHCs",
            "Prepare field teams for rapid deployment if escalation",
        ]
    else:
        advisories += [
            "Maintain weekly surveillance reporting",
        ]

    # Syndrome-specific
    advisories += SYNDROME_ADVISORIES.get(syndrome, [])

    # Hospital load
    if hospital_load_pct >= 85:
        advisories.append("[CAPACITY] Divert non-critical patients to secondary facilities immediately")
    elif hospital_load_pct >= 70:
        advisories.append("[CAPACITY] Review bed availability — load approaching critical threshold")

    # Water quality flag (from CSV)
    if water_quality_issue == 1:
        advisories.append("[WATER] Issue boil-water advisory for Ward area")

    # Sanitation risk
    if sanitation_score <= 4:
        advisories.append("[SANITATION] Fast-track sanitation inspection in low-scoring areas")

    return advisories

