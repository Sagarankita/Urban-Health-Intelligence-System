# MODEL 6 — Hotspot Zoning
# ═════════════════════════════════════════════════════════════
# Input:  ward_results list (from Model 5) + density_score from CSV
# Output: hotspot_score, top N wards, zone summary

def detect_hotspots(ward_results: list, top_n: int = 5) -> dict:
    for w in ward_results:
        # z-score contribution (capped at 30 pts)
        z_contrib = min(max(w["z_score"] * 10, 0), 30)

        # density multiplier from CSV
        density_mult = w.get("density_score", 1) / 3  # normalize to 0–1

        w["hotspot_score"] = round(
            0.55 * w["outbreak_prob"] +
            0.25 * z_contrib +
            0.20 * density_mult * 100,
            2
        )

    ranked = sorted(ward_results, key=lambda x: x["hotspot_score"], reverse=True)

    return {
        "top_hotspots": ranked[:top_n],
        "all_ranked":   ranked,
        "zone_summary": {
            z: [w["ward"] for w in ward_results if w["zone"] == z]
            for z in ["RED", "YELLOW", "GREEN"]
        }
    }

