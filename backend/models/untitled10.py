def score_hospital(hospital: dict, patient: dict) -> float:
    score = 0.0

    # Specialty match (hard requirement — skip if no match)
    if patient["needed_specialty"] not in hospital["specialties"]:
        return 0.0

    # Specialty match bonus
    score += 35

    # Capacity ratio
    cap_ratio = hospital["available_beds"] / hospital["total_beds"]
    score += cap_ratio * 25

    # Distance (closer = better, max 20 pts)
    dist_score = max(0, 10 - hospital["distance_km"]) * 2
    score += dist_score

    # PM-JAY match
    if patient.get("pmjay_beneficiary") and hospital["pmjay"]:
        score += 20

    return round(score, 2)

def recommend_hospitals(patient: dict, hospitals: list = SAMPLE_HOSPITALS, top_n: int = 3) -> list:
    scored = [(h, score_hospital(h, patient)) for h in hospitals]
    scored = [(h, s) for h, s in scored if s > 0]
    ranked = sorted(scored, key=lambda x: x[1], reverse=True)[:top_n]
    return [{"hospital": h["name"], "score": s, "pmjay": h["pmjay"], "beds_free": h["available_beds"]} for h, s in ranked]

