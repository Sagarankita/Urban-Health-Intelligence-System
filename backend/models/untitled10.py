def get_outbreak_data():
    """Returns outbreak detection results in JSON format for API consumption"""
    df, DAY_COLS = load_ward_data()
    results = []

    for _, row in df.iterrows():
        cases = [int(row[d]) for d in DAY_COLS]

        # Model 4
        trends = analyze_trends(cases)

        # Model 5
        warning = outbreak_warning(row["ward"], cases)

        # Attach metadata
        warning["syndrome"]           = row["syndrome"]
        warning["hospital_load_pct"]  = float(row["hospital_load_pct"])
        warning["pmjay_coverage_pct"] = float(row["pmjay_coverage_pct"])
        warning["density_score"]      = int(row["density_score"])
        warning["water_quality_issue"]= int(row["water_quality_issue"])
        warning["sanitation_score"]   = int(row["sanitation_score"])
        warning["nearest_hospital_km"]= float(row["nearest_hospital_km"])
        warning["wow_growth_pct"]     = trends["wow_growth_pct"]
        warning["growth_48h_pct"]     = trends["growth_48h_pct"]
        warning["moving_avg_7d"]      = trends["moving_avg_7d"]
        warning["seasonality"]        = trends["seasonality"]

        # Generate advisories
        warning["advisories"] = generate_advisory(
            warning["zone"], warning["syndrome"], warning["hospital_load_pct"],
            warning["water_quality_issue"], warning["sanitation_score"]
        )

        results.append(warning)

    # Hotspot zoning
    hotspots = detect_hotspots(results)

    # Symptom clusters from `reports` table
    ward_names = df["ward"].tolist() if "ward" in df.columns else []
    top_symptoms, ward_symptoms = compute_symptom_aggregates(ward_names)

    return {
        "zone_summary": hotspots["zone_summary"],
        "top_hotspots": hotspots["top_hotspots"],
        "all_wards": hotspots["all_ranked"],
        "top_symptoms": top_symptoms,
        "ward_symptoms": ward_symptoms,
        "timestamp": str(pd.Timestamp.now())
    }

