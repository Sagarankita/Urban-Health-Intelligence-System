# MODEL 4 — Trend Analyzer
# ═════════════════════════════════════════════════════════════
# Input:  ward row from CSV
# Output: moving_avg, wow_growth_pct, 48hr_growth, seasonality_flag

def analyze_trends(daily_cases: list) -> dict:
    n = len(daily_cases)

    # 7-day moving average (last value)
    moving_avg_last = round(
        sum(daily_cases[max(0, n - 7):]) / min(7, n), 1
    )

    # Week-over-week growth
    wow_growth = None
    if n >= 14:
        this_week = sum(daily_cases[-7:])
        last_week = sum(daily_cases[-14:-7])
        if last_week > 0:
            wow_growth = round((this_week - last_week) / last_week * 100, 1)

    # 48-hour growth rate (last 2 days vs 2 days before)
    growth_48h = None
    if n >= 4:
        recent2 = daily_cases[-1] + daily_cases[-2]
        prior2  = daily_cases[-3] + daily_cases[-4]
        if prior2 > 0:
            growth_48h = round((recent2 - prior2) / prior2 * 100, 1)

    # Monsoon seasonality flag (India: June–October)
    month = date.today().month
    seasonality = "MONSOON_RISK" if 6 <= month <= 10 else "NORMAL"

    return {
        "moving_avg_7d":  moving_avg_last,
        "wow_growth_pct": wow_growth,
        "growth_48h_pct": growth_48h,
        "seasonality":    seasonality,
    }

