# MODEL 1 — Symptom Severity & Risk Scoring
# ═════════════════════════════════════════════════════════════
# Input:  symptoms dict, age, comorbidities list, duration
# Output: risk_score (0–100), severity class

SYMPTOM_WEIGHTS = {
    "breathlessness": 25,
    "high_fever":     20,
    "vomiting":       15,
    "joint_pain":     10,
    "rash":           10,
    "cough":          10,
    "diarrhea":        8,
    "nausea":          6,
    "fatigue":         5,
}

def severity_score(symptoms: dict, age: int, comorbidities: list, duration_days: int) -> dict:
    """
    symptoms      : {"fever": True, "cough": True, ...}
    comorbidities : [True, False, ...]  (diabetes, asthma, heart_disease, etc.)
    """
    score = sum(SYMPTOM_WEIGHTS.get(s, 0) for s, active in symptoms.items() if active)

    # Age risk
    if age >= 60:    score += 15
    elif age <= 5:   score += 12
    elif age >= 45:  score +=  5

    # Comorbidity load
    score += sum(1 for c in comorbidities if c) * 10

    # Duration multiplier
    if duration_days >= 5:
        score = score * 1.2

    score = min(round(score), 100)

    if score >= 60:   severity = "High"
    elif score >= 35: severity = "Moderate"
    else:             severity = "Mild"

    return {"risk_score": score, "severity": severity}

