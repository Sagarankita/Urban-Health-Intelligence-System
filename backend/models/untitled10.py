def load_reports():
    """Load ward-level symptom weights from `reports` for city-wide + per-ward clustering."""
    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute("SELECT ward, symptoms FROM reports")
            rows = cur.fetchall()
        conn.close()
        return rows
    except Exception as e:
        print(f"Reports load failed: {e}. Using empty symptom aggregates.")
        return []


def normalize_symptom_value(v):
    # Accept numbers or booleans; ignore anything else.
    if v is None:
        return 0.0
    if isinstance(v, bool):
        return 1.0 if v else 0.0
    if isinstance(v, (int, float)):
        return float(v)
    try:
        return float(v)
    except Exception:
        return 0.0


def compute_symptom_aggregates(ward_names: list):
    """
    Returns:
      - top_symptoms: [{"name": str, "value": 0-100}, ...]
      - ward_symptoms: { wardName: [symptomName, ...], ... } (top 3)
    """
    city_counter = defaultdict(float)
    ward_counter = defaultdict(lambda: defaultdict(float))

    for row in load_reports():
        ward = row.get("ward")
        symptoms = row.get("symptoms") or {}
        if not isinstance(symptoms, dict):
            continue

        for symptom_name, raw_val in symptoms.items():
            weight = normalize_symptom_value(raw_val)
            if weight <= 0:
                continue
            city_counter[symptom_name] += weight
            if ward:
                ward_counter[ward][symptom_name] += weight

    city_sorted = sorted(city_counter.items(), key=lambda x: x[1], reverse=True)
    max_city = city_sorted[0][1] if city_sorted else 1.0

    top_symptoms = []
    for symptom_name, weight in city_sorted[:4]:
        # Normalize weights to 0..100 so UI bar widths are stable.
        value = int(round((weight / max_city) * 100))
        top_symptoms.append({"name": symptom_name, "value": value})

    # Per-ward top 3 with fallback to global top 3.
    global_top_names = [s["name"] for s in top_symptoms[:3]]
    ward_symptoms = {}
    for ward in ward_names:
        ward_sorted = sorted(
            ward_counter.get(ward, {}).items(),
            key=lambda x: x[1],
            reverse=True,
        )
        names = [name for name, _ in ward_sorted[:3]]
        if not names:
            names = global_top_names
        ward_symptoms[ward] = names

    return top_symptoms, ward_symptoms

